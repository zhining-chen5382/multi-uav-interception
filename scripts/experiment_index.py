def suggest_next_run(registry, version, seed=0, date_string=None, root=ROOT):
    """Return an unused identifier and path; no directory creation or training."""
    version_rows = {row["id"]: row for row in registry["versions"]}
    if version not in version_rows:
        raise ValueError("Unknown implemented version: " + version)
    if not _positive_integer(seed, allow_zero=True):
        raise ValueError("seed must be a nonnegative integer")
    date_string = datetime.now(SHANGHAI).strftime("%Y%m%d") if date_string is None else date_string
    if not isinstance(date_string, str) or not re.fullmatch(r"\d{8}", date_string):
        raise ValueError("date must use YYYYMMDD")
    datetime.strptime(date_string, "%Y%m%d")
    numbers = [int(row["id"].rsplit("-r", 1)[1]) for row in registry["runs"] if row["version"] == version]
    number = max(numbers, default=0) + 1
    output_root = version_rows[version].get("output_root", "outputs/" + version)
    directory = _version_output_directory(version_rows[version], root)
    while True:
        identity = "{}-r{:02d}".format(version, number)
        relative = "{}/{}_{}_seed{:03d}".format(output_root, identity, date_string, seed)
        if not _path(root, relative).exists() and not any(directory.glob(identity + "_*")):
            break
        number += 1
    current = version == registry["current_version"]
    command = None
    if current:
        config_path = _training_config_path(version_rows[version], root)
        entrypoint = _training_entrypoint(version_rows[version], root)
        if not version_rows[version].get("training_variants"):
            command = ("& .\\.venv\\Scripts\\python.exe -m {} --config {} "
                       "--seed {} --output-dir {}".format(entrypoint, config_path, seed, relative))
    if current and version_rows[version].get("training_variants"):
        note = "该版本包含多个配比组；需先选择对应配置。本命令只显示未使用Run编号，不选择组别或执行训练。"
    else:
        note = ("只显示建议；执行前确认当前配置仍匹配该版本，训练预算以配置或显式参数为准。" if current
                else "历史版本需要匹配其场景与奖励的配置；当前默认配置不能直接用于此版本。")
    return {"id": identity, "path": relative, "command": command,
            "note": note}


def write_indexes(registry, root=ROOT):
    """Write only the two generated navigation pages, preserving all artifacts."""
    errors = validate_registry(registry, root)
    if errors:
        raise ValueError("\n".join(errors))
    targets = [_path(root, "experiments/EXPERIMENT_INDEX.md"), _path(root, "outputs/README.md")]
    for target in targets:
        if target.exists() and not target.read_text(encoding="utf-8").startswith(GENERATED):
            raise ValueError("Refusing to overwrite a non-generated file: " + str(target))
    for target in targets:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render_index(registry, root, target), encoding="utf-8")
    return targets


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, default=DEFAULT_REGISTRY)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write-index", action="store_true")
    mode.add_argument("--next-run", metavar="VERSION")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--date", help="Suggested run date, YYYYMMDD; defaults to Asia/Shanghai today")
    args = parser.parse_args(argv)
    try:
        registry = load_registry(args.registry)
        errors = validate_registry(registry)
        if errors:
            raise ValueError("\n".join(errors))
        if args.write_index:
            print("\n".join(str(path) for path in write_indexes(registry)))
        elif args.next_run:
            print(json.dumps(suggest_next_run(registry, args.next_run, args.seed, args.date), ensure_ascii=False, indent=2))
        elif args.check:
            print("Registry OK: {} versions, {} runs, {} events, {} models; paths and checkpoint hashes verified.".format(
                len(registry["versions"]), len(registry["runs"]), len(registry["events"]), len(registry["models"])))
        else:
            print(render_index(registry), end="")
    except (OSError, ValueError, yaml.YAMLError) as error:
        parser.exit(1, str(error) + "\n")


if __name__ == "__main__":
    main()
