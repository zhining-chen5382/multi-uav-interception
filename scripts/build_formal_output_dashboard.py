    def build_version(self, version):
        directory = self.root/version["directory"]
        gallery = directory/"00_图表总览"
        rows = stage_rows(self.root,version)
        self.rows += rows
        groups = {}
        for row in rows:
            groups.setdefault((row["group"],row["seed"]),[]).append(row)
        quick = {key:self.build_quick(version,key[0],key[1],group_rows) for key,group_rows in groups.items()}
        figures = []
        for index,(source,label,category) in enumerate(overview_sources(version,rows)):
            record = self.copy_figure(source,gallery/('{:02d}_'.format(index+1)+label.replace(' · ','_')+'.png'),label,category)
            if record:
                figures.append(record)
        body = '<nav>{} {}</nav>'.format(link(gallery,self.root/"00_实验总览.html","全部版本"),link(gallery,directory/"README.md","版本说明"))
        body += '<section class=panel><h2>方案变化</h2><p>{}</p><p class=muted>{}</p>{}</section>'.format(
            escape(version["change"]),escape(version["purpose"]),result_table(rows,gallery,quick))
        body += '<div class=notice>优先看多Seed密集轨迹总览，再看每个Seed的Reward和Loss。不同累计训练步数分别标注。所有图直接来自已有实验文件，未重跑评估。</div>'
        body += '<div class=toolbar><input id=search placeholder="搜索Seed、阶段或图名" oninput="applySearch()">'
        for category,label in [('all','全部'),('trajectory','轨迹'),('capture','捕获率'),('reward','Reward'),('loss','Loss'),('diagnostics','优化诊断')]:
            body += '<button data-filter="{}" onclick="filterFigures(\'{}\')">{}</button>'.format(category,category,label)
        body += '</div>'
