class Builder:
    def __init__(self, repository, catalog):
        self.repository = Path(repository).resolve()
        self.catalog = catalog
        self.root = self.repository / catalog["root"]
        self.copies = []
        self.pages = []
        self.rows = []

    def write(self, target, text):
        write_generated(target, text)
        self.pages.append(target)

    def copy_figure(self, source, destination, label, category):
        source = Path(source)
        if not source.is_file():
            return None
        source_hash = sha(source)
        destination.parent.mkdir(parents=True, exist_ok=True)
        if destination.exists():
            if sha(destination) != source_hash:
                raise ValueError("Refusing to replace a differing copied figure: " + str(destination))
        else:
            shutil.copyfile(str(source), str(destination))
        assert sha(destination) == source_hash
        record = dict(source=str(source.relative_to(self.repository)).replace("\\", "/"),
            copy=str(destination.relative_to(self.repository)).replace("\\", "/"),
            sha256=source_hash, label=label, category=category)
        self.copies.append(record)
        return record

    def figure_html(self, record, directory, heading=None):
        image = self.repository / record["copy"]
        source = self.repository / record["source"]
        label = heading or record["label"]
        return '<section class="figure" data-category="{}"><h3>{}</h3><a href="{}"><img loading="lazy" src="{}" alt="{}"></a><p class="source">{} · SHA256 {}</p></section>'.format(
            record["category"], escape(label), href(directory,image), href(directory,image), escape(label),
            link(directory,source,"打开原图"),record["sha256"][:14])

    def videos(self, row, directory):
        blocks = []
        stage_root = row["run"].parent
        for model in ("best", "final"):
            reviewed = stage_root / "reviewed_videos_001" / row["run"].name / "videos" / model
            folder = reviewed if reviewed.exists() else row["post"] / "videos" / model
            video = folder / (model + "_full_episode.mp4")
            manifest = folder / (model + "_video_manifest.json")
            verification = folder / "decode_verification.json"
            if not (video.exists() and manifest.exists() and verification.exists()):
                blocks.append('<div class=panel><h3>{}</h3><p>未找到完整视频与核验资料。</p></div>'.format(model.title()))
                continue
            data = read_json(manifest)
            if not read_json(verification).get("all_checks_passed"):
                raise ValueError("Video decode check did not pass: " + str(verification))
            text = '{} · {:,}步 · {}° · {} · {}s'.format(model.title(), data["checkpoint_env_steps"],
                data["angle_degrees"], data["result"], round(data["simulation_seconds"],2))
            blocks.append('<div class=panel><h3>{}</h3><video controls preload="none" src="{}"></video><p class=source>{} · {}</p></div>'.format(
                escape(text),href(directory,video),link(directory,manifest,"视频来源manifest"),link(directory,verification,"完整解码核验")))
        return '<div class=videos>' + "".join(blocks) + '</div>'

    def quick_directory(self, version, group, seed):
        parent = self.root / version["directory"]
        if group:
            parent = parent / group
        return parent / ("run{:02d}_seed{}".format(version["seeds"].index(seed)+1,seed)) / "00_结果速览"

