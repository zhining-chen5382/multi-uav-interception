def sha(path):
    result = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            result.update(block)
    return result.hexdigest()


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def href(source_dir, target):
    return quote(os.path.relpath(str(target), str(source_dir)).replace("\\", "/"), safe="/.:#")


def link(source_dir, target, label):
    return '<a href="{}">{}</a>'.format(href(source_dir, target), escape(str(label)))


def percentage(value):
    return "未评估" if value is None else "{:.1f}%".format(100 * value)


