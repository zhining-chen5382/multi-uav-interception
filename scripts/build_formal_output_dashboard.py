def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog',type=Path,default=CATALOG)
    parser.add_argument('--write',action='store_true',help='Generate navigation after migration has completed')
    args=parser.parse_args()
    catalog=yaml.safe_load(args.catalog.read_text(encoding='utf-8'))
    if args.write:
        result=Builder(ROOT,catalog).build()
        print(json.dumps({k:result[k] for k in ('no_training','no_inference','stage_seed_rows')},ensure_ascii=False))
    else:
        root=ROOT/catalog['root']
        for move in catalog['moves']:
            if not ((root/move['new']).exists() or (root/move['old']).exists()):
                raise ValueError('Missing source and destination: '+str(move))
        print('Read-only check passed. Use --write after migration to create local navigation.')


if __name__=='__main__':
    main()
