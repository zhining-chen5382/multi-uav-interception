def write_generated(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and not path.read_text(encoding="utf-8").startswith(MARKER):
        raise ValueError("Refusing to overwrite a non-generated file: " + str(path))
    path.write_text(content, encoding="utf-8")


def reviewed_postprocessing(run, version_id, total_steps, group, seed):
    name = REVIEWED_POSTPROCESSING.get((version_id, total_steps, group, seed), "postprocessing_001")
    result = run / name
    manifest = result / "postprocessing_manifest.json"
    if not manifest.exists() or read_json(manifest).get("status") != "completed":
        raise ValueError("Reviewed postprocessing is not completed: " + str(result))
    return result


def evaluation_sources(run):
    """Old final_test means held-out Best, not the final policy checkpoint."""
    if (run / "best_test/summary.json").is_file():
        best, final = run / "best_test", run / "final_test"
    else:
        best, final = run / "final_test", run / "final_model_test"
    # Where available, prove the directory's model identity from saved evidence.
    for directory, model in ((best, "best"), (final, "final")):
        source = directory / "MODEL_SOURCE.json"
        if source.exists():
            checkpoint = read_json(source).get("checkpoint", "").replace("\\", "/")
            if checkpoint.rsplit("/", 1)[-1] != model + ".pt":
                raise ValueError("Evaluation model identity differs: " + str(source))
    return (best if (best / "summary.json").exists() else None,
            final if (final / "summary.json").exists() else None)


def training_capture(run):
    path = run / "episodes.csv"
    if not path.is_file():
        return None
    with path.open(encoding="utf-8-sig", newline="") as stream:
        rows = list(csv.DictReader(stream))
    return sum(r.get("captured") == "True" for r in rows) / len(rows) if rows else None


def research_run_id(version, group, seed):
    index = version["seeds"].index(seed) + 1
    if version["id"] == "v17" and group == "beta200_k0p01":
        index += len(version["seeds"])
    return "{}-r{:02d}".format(version["id"], index)


def stage_rows(root, version):
    rows = []
    for stage in version["stages"]:
        for seed in stage.get("seeds", version["seeds"]):
            run = root / version["directory"] / stage["directory"] / ("seed_" + str(seed))
            summary = read_json(run / "summary.json")
            if summary.get("status") != "completed" or summary["env_steps"] != stage["total_steps"]:
                raise ValueError("Incomplete or mismatched training stage: " + str(run))
            post = reviewed_postprocessing(run, version["id"], stage["total_steps"], stage.get("group"), seed)
            best_dir, final_dir = evaluation_sources(run)
            rows.append(dict(version=version["id"], seed=seed, group=stage.get("group"),
                run_id=research_run_id(version,stage.get("group"),seed),
                stage=stage, run=run, post=post, summary=summary,
                best_dir=best_dir, final_dir=final_dir,
                best_test=read_json(best_dir / "summary.json") if best_dir else None,
                final_test=read_json(final_dir / "summary.json") if final_dir else None,
                training_capture_rate=training_capture(run)))
    return rows


